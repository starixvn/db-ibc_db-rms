BEGIN
	DELETE dbo.rmSumWinloss_Old WITH (ROWLOCK, UPDLOCK) 
	WHERE winlostdate = @winlostdate
	SELECT @winlostdate = DATEADD(DAY,1,@winlostdate)
END

